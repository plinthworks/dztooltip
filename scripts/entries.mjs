/**
 * Every published entry compiled like a strict app would (DzGrid's `example.mjs entries`, after its 1.7.0 typings
 * imported an entry an app could not resolve): the packed tarballs (`npm run pack:local`) installed as copies in a
 * scratch Angular project outside the repository (the system's temporary folder, so nothing resolves from this
 * workspace's node_modules), with DzGrid from npm through the bridge's peer range —
 * no `legacy-peer-deps` there, so a peer range that cannot be met fails the install. One component imports every typed
 * entry of the four packages (read from their exports maps: a new entry is covered by itself), uses `[dzTooltip]` and
 * `[dzPopover]` in its template and puts `dzTooltips()` in a DzGrid `GridFeature[]`; ngc compiles it with strict
 * templates and `skipLibCheck: false`. Every other entry's file (the theme's sheets) must exist.
 *
 *   node scripts/entries.mjs [19 22]   the Angular majors to compile with (default: the oldest and the newest the peer range names; the owner's app is 21)
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PACKAGES = ['core', 'theme', 'angular', 'dzgrid'];
const majors = process.argv.slice(2).filter((a) => /^\d+$/.test(a));
const ENV = { ...process.env, NG_CLI_ANALYTICS: 'false', NO_COLOR: '1', FORCE_COLOR: '0', CI: '1', npm_config_legacy_peer_deps: 'false' };

function sh(cmd, argv, cwd) {
  console.log(`$ ${cmd} ${argv.join(' ')}   (in ${cwd})`);
  const r = spawnSync(cmd, argv, { cwd, env: ENV, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  process.stdout.write(`${r.stdout ?? ''}${r.stderr ?? ''}`);
  return r.status ?? 1;
}

const typed = (v) => typeof v === 'object' && v !== null && 'types' in v;
const target = (v) => (typeof v === 'string' ? v : v.default ?? Object.values(v)[0]);

function one(major) {
  const dir = join(tmpdir(), `dztooltip-entries-ng${major}`);
  const packed = readdirSync(join(ROOT, 'packed'));
  const tgz = Object.fromEntries(PACKAGES.map((p) => [p, packed.find((f) => f.startsWith(`dztooltip-${p}-`) && f.endsWith('.tgz'))]));
  const lost = PACKAGES.filter((p) => !tgz[p]);
  if (lost.length) throw new Error(`not packed: ${lost.join(', ')} — run npm run pack:local`);
  // The same version on every pack: the copies and their lock entries go, so npm installs the tarballs packed now.
  rmSync(join(dir, 'node_modules/@dztooltip'), { recursive: true, force: true });
  rmSync(join(dir, 'package-lock.json'), { force: true });
  rmSync(join(dir, 'src'), { recursive: true, force: true });
  mkdirSync(join(dir, 'src'), { recursive: true });
  const ng = `^${major}.0.0`;
  // TypeScript is an optional peer of Angular's compiler: the range that major asks, as an app would install it.
  const v = spawnSync('npm', ['view', `@angular/compiler-cli@${ng}`, 'peerDependencies.typescript', '--json'], { encoding: 'utf8', env: ENV });
  const ts = [JSON.parse(v.stdout || '""')].flat().pop();
  if (!ts) return { major, ok: false, why: 'the registry did not say which TypeScript' };
  writeFileSync(join(dir, 'package.json'), JSON.stringify({
    name: `dztooltip-entries-ng${major}`, private: true, type: 'module',
    dependencies: {
      ...Object.fromEntries(PACKAGES.map((p) => [`@dztooltip/${p}`, `file:${join(ROOT, 'packed', tgz[p])}`])),
      '@angular/core': ng, '@angular/common': ng, '@angular/compiler': ng, '@angular/compiler-cli': ng, typescript: ts,
    },
  }, null, 2) + '\n');
  writeFileSync(join(dir, '.npmrc'), 'legacy-peer-deps=false\n');
  if (sh('npm', ['install', '--prefer-offline', '--no-audit', '--no-fund'], dir) !== 0) return { major, ok: false, why: 'npm install failed (a peer range?)' };

  const manifests = PACKAGES.map((p) => JSON.parse(readFileSync(join(dir, 'node_modules/@dztooltip', p, 'package.json'), 'utf8')));
  const entries = [];
  const files = [];
  for (const { name, exports } of manifests)
    for (const [key, v] of Object.entries(exports ?? {})) {
      if (key === './package.json') continue;
      const entry = key === '.' ? name : `${name}/${key.slice(2)}`;
      if (typed(v)) entries.push(entry);
      else files.push(join(dir, 'node_modules', name, target(v)));
    }
  const missing = files.filter((f) => !existsSync(f));
  const names = entries.map((_, i) => `e${i}`);
  writeFileSync(join(dir, 'src/entries.ts'), [
    '// Generated by scripts/entries.mjs from the installed packages\' exports maps: do not edit.',
    `import { Component } from '@angular/core';`,
    `import type { GridFeature } from '@dzgrid/dom';`,
    `import { DzPopover, DzTooltip, type PopoverCloseReason } from '@dztooltip/angular';`,
    `import { dzTooltips } from '@dztooltip/dzgrid';`,
    `import { popover, safeHtml, tooltip } from '@dztooltip/core';`,
    ...entries.map((s, i) => `import * as ${names[i]} from '${s}';`),
    '',
    `export const features: GridFeature[] = [dzTooltips(), dzTooltips({ tone: 'neutral', placement: 'top', header: true, html: true, animation: 'morph' })];`,
    `export const page = (el: HTMLElement): void => {`,
    `  tooltip(el, { content: { html: '<b>x</b>' }, tone: 'success', placement: 'top-start', group: 'bar' }).destroy();`,
    `  popover(el, { content: () => safeHtml('<i>y</i>'), label: 'Details', onClose: (r: PopoverCloseReason) => void r }).destroy();`,
    `};`,
    '',
    `@Component({`,
    `  selector: 'x-entries',`,
    `  imports: [DzTooltip, DzPopover],`,
    '  template: `<button [dzTooltip]="\'Save\'" dzTooltipTone="success" dzTooltipPlacement="top" [dzTooltipDelay]="300">S</button>',
    '    <ng-template #t let-x let-close="close"><b>{{ x }}</b><button (click)="close()">ok</button></ng-template>',
    '    <button [dzPopover]="t" [dzPopoverContext]="\'ctx\'" dzPopoverPlacement="auto" #p="dzPopover" (closed)="last = $event">{{ p.isOpen() }}</button>`,',
    `})`,
    `export class Entries {`,
    `  last: PopoverCloseReason | null = null;`,
    `  readonly entries: readonly object[] = [${names.join(', ')}];`,
    `}`,
    '',
  ].join('\n'));
  writeFileSync(join(dir, 'tsconfig.json'), JSON.stringify({
    compilerOptions: {
      target: 'ES2022', module: 'ES2022', moduleResolution: 'bundler', lib: ['ES2023', 'DOM', 'DOM.Iterable'],
      strict: true, noImplicitOverride: true, noPropertyAccessFromIndexSignature: true, noImplicitReturns: true,
      exactOptionalPropertyTypes: true, noUncheckedIndexedAccess: true, skipLibCheck: false, noEmit: true, types: [],
    },
    angularCompilerOptions: { strictTemplates: true, strictInjectionParameters: true, strictInputAccessModifiers: true },
    files: ['src/entries.ts'],
  }, null, 2) + '\n');
  const status = sh(process.execPath, [join(dir, 'node_modules/@angular/compiler-cli/bundles/src/bin/ngc.js'), '-p', join(dir, 'tsconfig.json')], dir);
  const version = JSON.parse(readFileSync(join(dir, 'node_modules/@angular/core/package.json'), 'utf8')).version;
  return { major, version, ok: status === 0 && !missing.length, entries: entries.length, files: files.length, missing, why: status ? 'ngc failed' : '' };
}

const results = (majors.length ? majors : ['19', '22']).map(one);
console.log('\nentries (every published entry, strict Angular, skipLibCheck false):');
for (const r of results) {
  console.log(`  ${r.ok ? 'ok  ' : 'FAIL'} Angular ${r.version ?? r.major}: ${r.entries ?? 0} typed entries compiled, ${r.files ?? 0} other entries' files present${r.missing?.length ? `; missing ${r.missing.join(', ')}` : ''}${r.why ? ` — ${r.why}` : ''}`);
}
if (results.some((r) => !r.ok)) process.exitCode = 1;
